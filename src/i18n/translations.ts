let currentLang: Language = 'uz';

export function setLanguage(lang: Language) {
  currentLang = lang;
  try {
    localStorage.setItem('ilmtest_lang', lang);
  } catch (e) {}
}

export function getLanguage(): Language {
  try {
    const saved = localStorage.getItem('ilmtest_lang') as Language;
    if (saved && (saved === 'uz' || saved === 'en')) return saved;
  } catch (e) {}
  return 'uz';
}

export function t(key: keyof typeof translations['uz'], params?: Record<string, string | number>): string {
  const dict = translations[currentLang] || translations.uz;
  let str: string = (dict as any)[key] || translations.uz[key] || key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    });
  }
  return str;
}
